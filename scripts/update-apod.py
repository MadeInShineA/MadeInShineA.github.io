#!/usr/bin/env python3
"""Saves NASA's Astronomy Picture of the Day to assets/apod-data.js (the site's header image).

APOD moved to science.nasa.gov and the api.nasa.gov endpoint now returns a NASA logo
placeholder, so this reads the APOD page directly. Only metadata is stored; the image
itself is loaded from NASA's servers by the browser.

The data is written as a small script (window.APOD = {...}) rather than JSON so the
pages can load it with a <script> tag, which also works when they are opened from disk.

Usage: python3 scripts/update-apod.py [output-file]     (standard library only)

If today's APOD is a video or the page cannot be parsed, the existing file is kept.
"""

import html
import json
import re
import sys
import urllib.request
from datetime import datetime
from pathlib import Path

PAGE = "https://science.nasa.gov/apod/"
OUTPUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "assets" / "apod-data.js"


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "olivier.amacker.dev apod updater"})
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read().decode("utf-8", "replace")


def text(fragment: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", fragment))).strip()


def meta_row(page: str, label: str) -> str | None:
    for row in re.findall(r'<tr class="media-detail-hero__meta-row">(.*?)</tr>', page, re.S):
        head = re.search(r"<th[^>]*>(.*?)</th>", row, re.S)
        cell = re.search(r"<td[^>]*>(.*?)</td>", row, re.S)
        if head and cell and text(head.group(1)).lower().startswith(label.lower()):
            return text(cell.group(1))
    return None


def parse(page: str) -> dict | None:
    hero = page.find('class="media-detail-hero__media')
    if hero < 0:
        return None
    block = page[hero:hero + 20000]

    img = re.search(r'<img[^>]*\ssrc="([^"]+)"[^>]*>', block)
    title = re.search(r"<h2[^>]*>(.*?)</h2>", block, re.S)
    if not img or not title or "<iframe" in block[: block.find("<h2")]:
        return None  # video day, or the layout changed

    tag = img.group(0)
    image = html.unescape(img.group(1)).split("?")[0]
    if "nasa-logo" in image:
        return None
    link = re.search(r'<a href="(https://science\.nasa\.gov/image-article/[^"]+)"', block)
    alt = re.search(r'\salt="([^"]*)"', tag)

    date_text = meta_row(page, "Date")
    try:
        date = datetime.strptime(date_text, "%B %d, %Y").date().isoformat() if date_text else None
    except ValueError:
        date = None

    credit = meta_row(page, "Credit") or meta_row(page, "Image Credit")
    return {
        "date": date,
        "title": text(title.group(1)),
        "image": image,
        "alt": html.unescape(alt.group(1)) if alt else "",
        "link": link.group(1) if link else PAGE,
        "credit": credit,
        "copyright": meta_row(page, "Credit & Copyright") is not None,
    }


def main() -> int:
    try:
        data = parse(fetch(PAGE))
    except Exception as err:  # network or parsing problem: keep the previous picture
        print(f"warning: could not read APOD ({err}); keeping {OUTPUT.name}", file=sys.stderr)
        return 0
    if not data:
        print(f"Today's APOD is not a usable image; keeping {OUTPUT.name}")
        return 0
    OUTPUT.write_text(
        "// Generated by scripts/update-apod.py, do not edit by hand.\n"
        f"window.APOD = {json.dumps(data, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"Wrote APOD {data['date']}: {data['title']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
