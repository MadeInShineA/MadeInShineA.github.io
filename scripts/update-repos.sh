#!/usr/bin/env bash
# Fetches every public repository of a GitHub user through the GraphQL API
# and writes the flattened list to assets/repos-data.js (window.REPOS = [...]).
# It is a script rather than JSON so portfolio.html can load it with a <script>
# tag, which also works when the page is opened straight from disk.
#
# Usage:   GITHUB_TOKEN=<token> scripts/update-repos.sh [output-file]
# Token:   GITHUB_TOKEN or GH_TOKEN; falls back to `gh auth token` if the
#          GitHub CLI is installed and logged in. A classic token with no
#          scopes (public data only) is enough.
# Needs:   bash, curl, jq   (on NixOS: nix shell nixpkgs#jq -c scripts/update-repos.sh)

set -euo pipefail

GITHUB_USER="${GITHUB_USER:-MadeInShineA}"
OUTPUT="${1:-$(dirname "$0")/../assets/repos-data.js}"

TOKEN="${GITHUB_TOKEN:-${GH_TOKEN:-}}"
if [[ -z "$TOKEN" ]] && command -v gh >/dev/null 2>&1; then
  TOKEN="$(gh auth token 2>/dev/null || true)"
fi
if [[ -z "$TOKEN" ]]; then
  echo "error: no GitHub token found. Either:" >&2
  echo "  - run: GITHUB_TOKEN=<token> $0   (any token, no scopes needed), or" >&2
  echo "  - log in once with 'gh auth login' and run this again with gh on your PATH" >&2
  exit 1
fi

for bin in curl jq; do
  command -v "$bin" >/dev/null 2>&1 || { echo "error: '$bin' is required" >&2; exit 1; }
done

# Small pages keep each query fast: counting the commits of big forks (nixpkgs, rust...)
# is expensive, and GitHub answers 502 when a query runs too long.
PAGE_SIZE="${PAGE_SIZE:-25}"
MAX_ATTEMPTS=4

# shellcheck disable=SC2016  # $login/$cursor/$size are GraphQL variables, not shell ones
QUERY='query($login: String!, $cursor: String, $size: Int!) {
  user(login: $login) {
    repositories(first: $size, after: $cursor, privacy: PUBLIC, orderBy: {field: UPDATED_AT, direction: DESC}) {
      pageInfo { hasNextPage endCursor }
      nodes {
        name
        description
        url
        stargazerCount
        updatedAt
        owner { login }
        languages(first: 10, orderBy: {field: SIZE, direction: DESC}) { nodes { name } }
        defaultBranchRef { target { ... on Commit { history { totalCount } } } }
      }
    }
  }
}'

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# POST a GraphQL payload, retrying temporary failures (5xx, timeouts, rate limiting)
graphql() {
  local payload="$1" out="$2" attempt status
  for ((attempt = 1; attempt <= MAX_ATTEMPTS; attempt++)); do
    status="$(curl -sS -o "$out" -w '%{http_code}' --max-time 60 \
      -H "Authorization: bearer $TOKEN" \
      -H "Content-Type: application/json" \
      -d "$payload" \
      https://api.github.com/graphql)" || true
    status="${status:-000}"

    if [[ "$status" == 200 ]]; then
      return 0
    fi
    if [[ "$status" =~ ^(000|403|429|5[0-9][0-9])$ && $attempt -lt $MAX_ATTEMPTS ]]; then
      echo "GitHub answered HTTP $status, retrying in $((attempt * 5))s ($attempt/$((MAX_ATTEMPTS - 1)))" >&2
      sleep $((attempt * 5))
      continue
    fi
    echo "error: GitHub answered HTTP $status" >&2
    head -c 500 "$out" >&2 2>/dev/null || true
    echo >&2
    return 1
  done
}

cursor=null
page=0
while :; do
  page=$((page + 1))
  file="$tmp/page-$(printf %03d "$page").json"
  payload="$(jq -n --arg q "$QUERY" --arg login "$GITHUB_USER" --argjson cursor "$cursor" \
    --argjson size "$PAGE_SIZE" '{query: $q, variables: {login: $login, cursor: $cursor, size: $size}}')"

  graphql "$payload" "$file"

  if jq -e '.errors' "$file" >/dev/null; then
    echo "error: GraphQL query failed:" >&2
    jq '.errors' "$file" >&2
    exit 1
  fi

  [[ "$(jq -r '.data.user.repositories.pageInfo.hasNextPage' "$file")" == "true" ]] || break
  cursor="$(jq '.data.user.repositories.pageInfo.endCursor' "$file")"
done

jq -s '
  [ .[].data.user.repositories.nodes[]
    | {
        name,
        description,
        url,
        stargazerCount,
        updatedAt,
        owner: { login: .owner.login },
        commits: (.defaultBranchRef.target.history.totalCount // 0),
        languages: [ .languages.nodes[].name ]
      }
  ]' "$tmp"/page-*.json > "$tmp/repos.json"

{
  echo "// Generated by scripts/update-repos.sh, do not edit by hand."
  printf 'window.REPOS = '
  jq . "$tmp/repos.json"
  echo ';'
} > "$tmp/repos-data.js"
mv "$tmp/repos-data.js" "$OUTPUT"
echo "Wrote $(jq length "$tmp/repos.json") repositories to $OUTPUT"
